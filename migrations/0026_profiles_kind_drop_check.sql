-- kind 의 값 집합을 바꾸기 위한 3단(0026~0028) 중 첫 단계. 0012 가 건 CHECK 를 뗀다.
--
-- 'self'/'other' 를 'saved' 하나로 합친다. 둘을 가르던 축이 잘못돼 있었다:
-- 'other' 가 실제로 나르던 뜻은 "이 사람은 남이다" 가 아니라 "이 사람은 나의 대역이
-- 아니다" 였고, 그래서 같은 사람이 어느 문(홈 / 궁합)으로 들어왔느냐만으로 "나" 칸에
-- 설 수 있는지가 갈렸다. 정작 "나" 가 필요한 자리(상담 대상, 지도 중심)는 kind 로
-- 답할 수 없어 각자 다른 휴리스틱(최신 / 가장 오래된 것)을 쓰고 있었다.
--
-- 이제 kind 는 사용자가 고른 것 하나만 나른다: 저장할 것인가('saved') 이번만인가('temp').
-- "누가 나인가" 는 users.primary_profile_id 가 답한다 (0029).
--
-- 값을 먼저 바꿀 수 없어 제약을 먼저 떼어낸다 — 'saved' 는 지금 CHECK 를 통과하지 못하고,
-- 반대로 새 CHECK 를 먼저 걸면 남아 있는 'self'/'other' 행이 검증에 걸린다.
ALTER TABLE profiles DROP CONSTRAINT IF EXISTS profiles_kind_check;
