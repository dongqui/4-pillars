//
// 왜 필요한가: [사실] 블록만 주면 모델이 매 답마다 항목의 뜻을 고민에 맞춰 새로
// 지어낸다. 실측(2026-09-16)에서 같은 사주의 비겁을 "싫은 소리를 못 해요" 에는
