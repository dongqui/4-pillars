/** 기준 id 모음. 모델이 없는 id 를 지어냈는지 보는 데 쓴다 */
export function criterionIds(list: Criterion[]): Set<string> {
  return new Set(list.map((c) => c.id));
}

/**
 * 프롬프트에 붙일 블록. 계산 사실과 갈라 놓는 머리말이 이 블록의 절반이다 —
 * "서비스가 채택한 해석"이라고 말해 두지 않으면 모델이 이것도 계산 결과로 읽는다.
 */
export function renderCriteria(list: Criterion[]): string {
  if (list.length === 0) return "";
  const body = list
    .map((c) =>
      [
        `### ${c.id} (${c.kind})`,
        `- 근거 항목: ${c.basis}`,
        `- 적용 조건: ${c.when}`,
        `- 허용하는 해석: ${c.allows}`,
        `- 이 근거로 판단할 수 없는 것: ${c.cannot}`,
        `- 쉬운 표현: ${c.plain}`,
      ].join("\n"),
    )
    .join("\n\n");
  return [
    "[해석 기준]",
    "※ 아래는 계산 결과가 아니라 서비스가 미리 정해 둔 읽는 법이다. 질문을 보기 전에 정해졌다.",
    "※ 사주로 무언가를 설명하려면 여기 있는 기준에서 출발한다. 기준의 허용 범위와 적용 조건을 이번 질문에 맞춰 바꾸지 않는다.",
    "※ \"판단할 수 없는 것\" 은 말을 약하게 바꿔도 여전히 판단 밖이다. 경험이 많은지 적은지처럼 사용자가 말해 주지 않은 이력도 기준으로 추정하지 않는다.",
    "",
    body,
  ].join("\n");
}
