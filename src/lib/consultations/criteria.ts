// 프롬프트에 금지 문장을 더 쌓아도 막히지 않았다 — 그래서 뜻을 질문보다 **먼저**
// 고정해 두고, 질문은 그중 무엇을 고를지에만 쓰게 한다.
//
// ⚠️ 이것은 계산 결과가 아니라 **채택한 해석**이다. [사실] 블록과 한 덩어리로 섞지
// 않는다(renderCriteria 가 머리말로 갈라 준다). 여기 적힌 문구가 고정됐다는 것은
// 일관성 실험을 할 수 있다는 뜻이지, 명리적으로 검증됐다는 뜻이 아니다.
//
// ⚠️ 범위: 아래 세트는 실험용 초안이고 **테스트 사주 한 벌 전용**이다(TEST_CHART).
// 운영 전체에 쓸 해석 사전이 아니다. 다른 사주에 붙이려면 그 사주의 계산 항목을
// 보고 다시 쓴다 — 항목 이름이 같다고 조건과 범위까지 같지 않다.

/**
 * 기준 하나. 다섯 칸이 모두 채워져야 한다 — 특히 `cannot` 이 비면 모델이 허용
 * 해석을 아무 데나 늘려 쓴다. 이 칸이 실험의 핵심이다.
 */
export interface Criterion {
  /** 모델이 basis 로 돌려줄 짧은 id. 사람이 로그에서 알아볼 수 있게 짓는다 */
  id: string;
  /** 근거가 되는 계산 항목. [사실] 블록에서 그대로 확인할 수 있는 것만 */
  basis: string;
  /** 적용 조건 — 어떤 장면의 질문에서 이 기준을 쓸 수 있는가 */
  when: string;
  /** 허용하는 해석. 이 방향을 질문에 맞춰 뒤집지 않는다 */
  allows: string;
  /** 이 근거만으로는 판단할 수 없는 것 */
  cannot: string;
  /** 사용자에게 설명할 쉬운 표현 */
  plain: string;
  /** 원국(오래 가는 성향)인지 흐름(지나가는 시기)인지 */
  kind: "원국" | "흐름";
}

